const dict: Record<Lang, Record<Key, string>> = { en, bn }

export const makeT = (lang: Lang) => (k: Key, vars?: Record<string, string | number>) => {
  let s = dict[lang][k] ?? en[k]
  if (vars) for (const [name, v] of Object.entries(vars)) s = s.split(`{${name}}`).join(String(v))
  return s
}
